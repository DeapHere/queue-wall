package queuewall;

import java.io.File;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import net.minecraft.client.Minecraft;
import net.minecraft.client.SurvivalInteractionManager;
import net.minecraft.util.math.Vec3i;
import net.minecraft.world.World;
import net.minecraft.world.WorldSettings;
import queuewall.compat.Versions;

/**
 * Development only (./gradlew runGenTest): checks that worlds made by the queue are block-for-block the same as
 * worlds made by Create New World.
 *
 * 1. Reference: for each seed, the game's own startGame, exactly what Create New World calls, on the main thread.
 * 2. Queue: the same seeds generated by QueuedWorld on several generator threads at once, a few rounds.
 * 3. Play: one queued world played through QueueWall.play, the way the wall plays it.
 *
 * Each world is hashed over every block id and metadata value within 120 blocks of spawn, plus the spawn point.
 */
public final class GenerationTest {
    private static final int SEEDS = 12;
    private static final int ROUNDS = 3;

    public static int run(Minecraft mc) {
        QueueWall.init(mc);
        int threads = Integer.getInteger("queuewall.gentest.threads", 4);
        long[] seeds = new long[SEEDS];
        for (int i = 0; i < SEEDS; i++) seeds[i] = 1000L + i * 7919L;
        int failures = 0;
        try {
            Map<Long, Long> reference = new LinkedHashMap<>();
            long t = System.currentTimeMillis();
            for (long seed : seeds) reference.put(seed, createNewWorld(mc, "gentest-ref-" + seed, seed));
            log("reference: " + SEEDS + " worlds through startGame in " + (System.currentTimeMillis() - t) + " ms");
            // the reference again, to see that vanilla itself gives the same world each time
            for (long seed : seeds) {
                long again = createNewWorld(mc, "gentest-ref2-" + seed, seed);
                if (again != reference.get(seed)) {
                    log("reference differs between two Create New World runs for seed " + seed + ": " + firstDiff.get(seed));
                    reference.put(seed, again);
                }
            }
            log("reference repeated");

            WorldQueue queue = new WorldQueue(mc, QueueWall.cfg);
            for (int round = 0; round < ROUNDS; round++) {
                ExecutorService pool = Executors.newFixedThreadPool(threads, r -> new GenThread(r, "gentest generator"));
                Map<Long, Future<Long>> results = new LinkedHashMap<>();
                t = System.currentTimeMillis();
                for (long seed : seeds) {
                    QueuedWorld q = new QueuedWorld("gentest-q" + round + "-" + seed, seed);
                    results.put(seed, pool.submit(() -> {
                        q.generate(mc, mc.getWorldStorageSource(), queue);
                        if (!q.isReady()) throw new IllegalStateException(q.folder + " ended " + q.state);
                        return hash(q.world);
                    }));
                }
                int bad = 0;
                for (Map.Entry<Long, Future<Long>> e : results.entrySet()) {
                    try {
                        if (!e.getValue().get().equals(reference.get(e.getKey()))) {
                            bad++;
                            log("MISMATCH seed " + e.getKey());
                        }
                    } catch (Exception ex) {
                        bad++;
                        log("seed " + e.getKey() + " failed: " + ex);
                    }
                }
                pool.shutdown();
                failures += bad;
                log("queue round " + round + ": " + SEEDS + " worlds on " + threads + " threads in " + (System.currentTimeMillis() - t)
                        + " ms, " + (SEEDS - bad) + "/" + SEEDS + " identical to the reference");
            }

            // played the way the wall plays a world: startGame with the queued world handed in
            long seed = seeds[0];
            QueuedWorld q = new QueuedWorld("gentest-play-" + seed, seed);
            Thread g = new GenThread(() -> q.generate(mc, mc.getWorldStorageSource(), queue), "gentest generator");
            g.start();
            g.join();
            QueueWall.queue = queue;
            QueueWall.play(mc, q);
            boolean same = mc.world == q.world && hash(mc.world) == reference.get(seed);
            log("played queued world: " + (same ? "identical to the reference" : "MISMATCH"));
            if (!same) failures++;
            mc.setWorld(null);
        } catch (Throwable e) {
            e.printStackTrace();
            failures++;
        }
        log(failures == 0 ? "PASSED" : "FAILED (" + failures + ")");
        return failures == 0 ? 0 : 1;
    }

    /** Create New World with this seed: survival, structures on, not hardcore. Returns the world's hash. */
    private static final Map<Long, int[]> snapshots = new LinkedHashMap<>();
    private static final Map<Long, String> firstDiff = new LinkedHashMap<>();

    private static long createNewWorld(Minecraft mc, String folder, long seed) {
        mc.interactionManager = new SurvivalInteractionManager(mc);
        mc.startGame(folder, "New World", Versions.newWorldSettings(seed));
        long h = hash(mc.world);
        int[] snap = snapshot(mc.world);
        int[] before = snapshots.put(seed, snap);
        if (before != null) {
            Vec3i sp = mc.world.getSpawnPoint();
            int n = 0;
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < snap.length; i++) {
                if (snap[i] != before[i]) {
                    if (n < 8) {
                        int y = i % 128, z = (i / 128) % 240 - 120, x = i / 128 / 240 - 120;
                        sb.append(" (").append(sp.x + x).append(",").append(y).append(",").append(sp.z + z).append(" ").append(before[i]).append("->").append(snap[i]).append(")");
                    }
                    n++;
                }
            }
            firstDiff.put(seed, n + " blocks differ, spawn " + sp.x + "," + sp.y + "," + sp.z + sb);
        }
        mc.setWorld(null);
        return h;
    }

    private static int[] snapshot(World w) {
        Vec3i spawn = w.getSpawnPoint();
        int[] out = new int[240 * 240 * 128];
        int i = 0;
        for (int x = -120; x < 120; x++)
            for (int z = -120; z < 120; z++)
                for (int y = 0; y < 128; y++)
                    out[i++] = w.getBlock(spawn.x + x, y, spawn.z + z) << 4 | w.getBlockMetadata(spawn.x + x, y, spawn.z + z);
        return out;
    }

    private static long hash(World w) {
        Vec3i spawn = w.getSpawnPoint();
        long h = 1469598103934665603L;
        h = h * 31 + spawn.x;
        h = h * 31 + spawn.y;
        h = h * 31 + spawn.z;
        for (int x = -120; x < 120; x++) {
            for (int z = -120; z < 120; z++) {
                for (int y = 0; y < 128; y++) {
                    h = (h ^ w.getBlock(spawn.x + x, y, spawn.z + z)) * 1099511628211L;
                    h = (h ^ w.getBlockMetadata(spawn.x + x, y, spawn.z + z)) * 1099511628211L;
                }
            }
        }
        return h;
    }

    private static void log(String s) {
        System.out.println("[gentest] " + s);
    }

    private GenerationTest() {}
}
